def generate_expanded_word_corpus() -> List[Tuple[str, int]]:
    """Generate a rich, diversified word corpus containing only authentic, dictionary-attested Japanese words."""
    words_dict: Dict[str, int] = {}
    
    # Base vocabulary seeds (Strictly vetted authentic Japanese words, 2-8 morae)
    for w, freq in _BASE_VOCABULARY:
        nw = normalize_text(w)
        words_dict[nw] = max(words_dict.get(nw, 0), freq)

    # Return sorted list of (word, weight)
    result = sorted(words_dict.items(), key=lambda x: (-x[1], x[0]))
    return result


def setup_word_corpus(corpus_dir: str = "data/corpus") -> str:
    """Ensure words_corpus.json exists in data/corpus/."""
    os.makedirs(corpus_dir, exist_ok=True)
    words_path = os.path.join(corpus_dir, "words_corpus.json")
    if not os.path.exists(words_path):
        word_list = generate_expanded_word_corpus()
        with open(words_path, "w", encoding="utf-8") as f:
            json.dump(word_list, f, ensure_ascii=False, indent=2)
    return words_path

def get_word_corpus(corpus_dir: str = "data/corpus") -> List[Tuple[str, int]]:
    """Get the expanded Japanese word corpus (list of (hiragana_word, frequency_weight))."""
    words_path = os.path.join(corpus_dir, "words_corpus.json")
    if not os.path.exists(words_path):
        setup_word_corpus(corpus_dir)
    with open(words_path, "r", encoding="utf-8") as f:
        data = json.load(f)
        return [(item[0], item[1]) for item in data]


